CREATE COLUMN TABLE CASE_CATEGORIES (
  CATEGORY_ID NVARCHAR(80) PRIMARY KEY,
  CATEGORY_NAME NVARCHAR(160) NOT NULL,
  DESCRIPTION NVARCHAR(1000)
);

CREATE COLUMN TABLE LAW_METADATA (
  SOURCE_ID NVARCHAR(120) PRIMARY KEY,
  TITLE NVARCHAR(500) NOT NULL,
  AUTHORITY NVARCHAR(300),
  JURISDICTION NVARCHAR(120) NOT NULL,
  CATEGORY_ID NVARCHAR(80) NOT NULL,
  SOURCE_URL NVARCHAR(2000),
  SOURCE_TYPE NVARCHAR(100),
  REVIEW_STATUS NVARCHAR(80) DEFAULT 'pending_review'
);

CREATE COLUMN TABLE LAW_CHUNKS (
  CHUNK_ID NVARCHAR(120) PRIMARY KEY,
  SOURCE_ID NVARCHAR(120) NOT NULL,
  CONTENT NCLOB NOT NULL,
  EMBEDDING_MODEL NVARCHAR(300),
  EMBEDDING REAL_VECTOR(384)
);

